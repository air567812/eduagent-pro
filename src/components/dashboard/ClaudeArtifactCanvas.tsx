'use client';

import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  X,
  Maximize2,
  Minimize2,
  Copy,
  Check,
  Download,
  FileText,
  FileCode,
  Layers,
  Sparkles,
  RotateCw,
  CheckCircle2,
  XCircle
} from 'lucide-react';
import { useToast } from '@/components/ui/Toast';

interface ArtifactProps {
  isOpen: boolean;
  onClose: () => void;
  artifact: {
    id: string;
    title: string;
    type: 'FLASHCARDS' | 'MCQ' | 'NOTES' | 'REPORT' | 'QUESTIONS';
    data: any;
    createdAt?: string;
  } | null;
}

export default function ClaudeArtifactCanvas({
  isOpen,
  onClose,
  artifact
}: ArtifactProps) {
  const { success } = useToast();
  const [copied, setCopied] = useState(false);
  const [isExpanded, setIsExpanded] = useState(false);

  // Flashcards state
  const [activeCardIdx, setActiveCardIdx] = useState(0);
  const [isFlipped, setIsFlipped] = useState(false);

  // MCQ state
  const [mcqAnswers, setMcqAnswers] = useState<{ [qIdx: number]: number }>({});

  if (!isOpen || !artifact) return null;

  const handleCopy = () => {
    const textContent = JSON.stringify(artifact.data, null, 2);
    navigator.clipboard.writeText(textContent);
    setCopied(true);
    success('Copied to Clipboard!', 'Study artifact copied successfully.');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = (format: 'md' | 'txt' | 'json') => {
    let content = '';
    let mime = 'text/plain';

    if (format === 'json') {
      content = JSON.stringify(artifact.data, null, 2);
      mime = 'application/json';
    } else {
      content = `# ${artifact.title}\n\nGenerated by EduAgent Pro AI Engine\n\n${JSON.stringify(artifact.data, null, 2)}`;
    }

    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${artifact.title.replace(/\s+/g, '_').toLowerCase()}.${format}`;
    a.click();
    URL.revokeObjectURL(url);
    success('Export Complete', `Saved as .${format.toUpperCase()}`);
  };

  return (
    <>
      {/* Mobile backdrop overlay */}
      <div
        onClick={onClose}
        className="fixed inset-0 bg-black/60 backdrop-blur-sm z-40 md:hidden"
      />

      {/* Artifact Sheet / Dock Container */}
      <motion.aside
        initial={{ y: 300, opacity: 0 }}
        animate={{ y: 0, opacity: 1 }}
        exit={{ y: 300, opacity: 0 }}
        transition={{ type: 'spring', damping: 25, stiffness: 220 }}
        className={`fixed z-50 flex flex-col bg-[#111827] text-slate-100 border border-slate-800 shadow-[0_20px_70px_rgba(0,0,0,0.8)] overflow-hidden select-none transition-all
          /* Mobile styles: Bottom Sheet */
          inset-x-0 bottom-0 top-auto h-[85vh] max-h-[85vh] rounded-t-[28px] rounded-b-none
          /* Desktop styles: Docked Right Drawer */
          md:inset-x-auto md:top-20 md:right-4 md:bottom-4 md:h-auto md:max-h-none md:rounded-[28px]
          ${isExpanded ? 'md:w-[860px]' : 'md:w-[500px] lg:w-[540px]'}
        `}
      >
        {/* Mobile Pull Handle Indicator */}
        <div className="md:hidden flex justify-center pt-2.5 pb-1">
          <div className="w-10 h-1 rounded-full bg-slate-700" />
        </div>

        {/* Top Action Bar */}
        <div className="p-4 border-b border-slate-800 bg-slate-900/60 flex items-center justify-between gap-3">
          <div className="flex items-center gap-2.5 min-w-0">
            <div className="w-8 h-8 rounded-xl bg-blue-600/20 border border-blue-500/30 flex items-center justify-center text-blue-400 flex-shrink-0">
              <Sparkles className="w-4 h-4" />
            </div>
            <div className="min-w-0">
              <div className="flex items-center gap-2">
                <span className="text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded-full bg-blue-500/20 text-blue-400 border border-blue-500/30">
                  Artifact Canvas
                </span>
                <span className="text-[10px] text-slate-400">Interactive View</span>
              </div>
              <h3 className="text-sm font-bold text-white truncate mt-0.5">{artifact.title}</h3>
            </div>
          </div>

          {/* Action buttons */}
          <div className="flex items-center gap-1.5 flex-shrink-0">
            <button
              onClick={handleCopy}
              className="p-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 text-xs font-semibold flex items-center transition-colors"
              title="Copy Content"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            </button>

            <button
              onClick={() => handleDownload('md')}
              className="p-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 text-xs font-semibold flex items-center transition-colors"
              title="Export as Markdown"
            >
              <Download className="w-3.5 h-3.5" />
            </button>

            <button
              onClick={() => setIsExpanded(!isExpanded)}
              className="p-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 transition-colors hidden md:block"
              title={isExpanded ? 'Collapse Canvas' : 'Expand Canvas'}
            >
              {isExpanded ? <Minimize2 className="w-3.5 h-3.5" /> : <Maximize2 className="w-3.5 h-3.5" />}
            </button>

            <button
              onClick={onClose}
              className="p-2 rounded-xl bg-slate-800 hover:bg-rose-500/20 text-slate-300 hover:text-rose-400 border border-slate-700 transition-colors"
              title="Close Artifact"
            >
              <X className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>

        {/* Scrollable Canvas Body */}
        <div className="flex-1 overflow-y-auto p-4 sm:p-5 space-y-6">
          {/* Flashcards View */}
          {artifact.type === 'FLASHCARDS' && Array.isArray(artifact.data?.flashcards || artifact.data) && (
            (() => {
              const cards = artifact.data?.flashcards || artifact.data;
              const currentCard = cards[activeCardIdx] || { question: 'No question', answer: 'No answer' };

              return (
                <div className="space-y-4">
                  <div className="flex items-center justify-between text-xs font-bold text-slate-400">
                    <span className="flex items-center gap-1.5">
                      <Layers className="w-4 h-4 text-blue-400" /> Card {activeCardIdx + 1} of {cards.length}
                    </span>
                    <span className="text-[11px] text-slate-400">Tap card to flip</span>
                  </div>

                  <div
                    onClick={() => setIsFlipped(!isFlipped)}
                    className="cursor-pointer min-h-[220px] rounded-2xl p-6 bg-slate-900 border border-slate-800 hover:border-blue-500/50 flex flex-col justify-between transition-all select-none shadow-md"
                  >
                    <div className="flex items-center justify-between">
                      <span className="text-[10px] font-bold uppercase tracking-wider text-blue-400">
                        {isFlipped ? 'Answer' : 'Question / Prompt'}
                      </span>
                      <RotateCw className="w-3.5 h-3.5 text-slate-500" />
                    </div>

                    <p className="text-base font-bold text-center text-white my-auto py-4 leading-relaxed">
                      {isFlipped
                        ? currentCard.answer || currentCard.back
                        : currentCard.question || currentCard.front}
                    </p>

                    <div className="text-center text-[10px] text-slate-500">
                      Tap anywhere to flip card
                    </div>
                  </div>

                  {/* Navigation */}
                  <div className="flex items-center justify-between gap-3">
                    <button
                      disabled={activeCardIdx === 0}
                      onClick={() => {
                        setIsFlipped(false);
                        setActiveCardIdx((prev) => Math.max(0, prev - 1));
                      }}
                      className="px-4 py-2 rounded-xl bg-slate-800 text-xs font-semibold text-slate-200 border border-slate-700 disabled:opacity-30"
                    >
                      ← Prev
                    </button>
                    <span className="text-xs text-slate-400 font-medium">
                      {activeCardIdx + 1} / {cards.length}
                    </span>
                    <button
                      disabled={activeCardIdx === cards.length - 1}
                      onClick={() => {
                        setIsFlipped(false);
                        setActiveCardIdx((prev) => Math.min(cards.length - 1, prev + 1));
                      }}
                      className="px-4 py-2 rounded-xl bg-blue-600 hover:bg-blue-500 text-xs font-semibold text-white disabled:opacity-30"
                    >
                      Next →
                    </button>
                  </div>
                </div>
              );
            })()
          )}

          {/* MCQ Quiz View */}
          {artifact.type === 'MCQ' && (
            <div className="space-y-4">
              {(artifact.data?.questions || artifact.data || []).map((q: any, qIdx: number) => {
                const selectedOpt = mcqAnswers[qIdx];
                const isAnswered = selectedOpt !== undefined;
                const isCorrect = isAnswered && selectedOpt === q.correctAnswerIndex;

                return (
                  <div
                    key={qIdx}
                    className="p-4 sm:p-5 rounded-2xl bg-slate-900/80 border border-slate-800 space-y-3"
                  >
                    <p className="text-xs sm:text-sm font-bold text-white">
                      <span className="text-blue-400 mr-1.5">Q{qIdx + 1}.</span> {q.question}
                    </p>

                    <div className="space-y-2">
                      {(q.options || []).map((opt: string, optIdx: number) => {
                        let btnStyle = 'bg-slate-950/60 border-slate-800 text-slate-300 hover:border-slate-700';
                        if (isAnswered) {
                          if (optIdx === q.correctAnswerIndex) {
                            btnStyle = 'bg-emerald-950/50 border-emerald-500/60 text-emerald-200 font-bold';
                          } else if (selectedOpt === optIdx) {
                            btnStyle = 'bg-rose-950/50 border-rose-500/60 text-rose-200';
                          } else {
                            btnStyle = 'opacity-40 bg-slate-950 border-slate-900 text-slate-500';
                          }
                        }

                        return (
                          <button
                            key={optIdx}
                            disabled={isAnswered}
                            onClick={() => setMcqAnswers((prev) => ({ ...prev, [qIdx]: optIdx }))}
                            className={`w-full p-3 rounded-xl border text-xs text-left flex items-center justify-between transition-all ${btnStyle}`}
                          >
                            <span>{opt}</span>
                            {isAnswered && optIdx === q.correctAnswerIndex && (
                              <CheckCircle2 className="w-4 h-4 text-emerald-400 flex-shrink-0" />
                            )}
                            {isAnswered && selectedOpt === optIdx && optIdx !== q.correctAnswerIndex && (
                              <XCircle className="w-4 h-4 text-rose-400 flex-shrink-0" />
                            )}
                          </button>
                        );
                      })}
                    </div>

                    {isAnswered && q.explanation && (
                      <div className="p-3 rounded-xl text-xs bg-slate-950 border border-slate-800 text-slate-300 space-y-1">
                        <strong className="text-blue-400 block font-semibold">Explanation:</strong>
                        <p>{q.explanation}</p>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          )}

          {/* Structured Notes / Fallback View */}
          {artifact.type !== 'FLASHCARDS' && artifact.type !== 'MCQ' && (
            <div className="p-5 rounded-2xl bg-slate-900/80 border border-slate-800 text-slate-200 text-xs sm:text-sm leading-relaxed">
              {typeof artifact.data === 'string' ? (
                <div className="whitespace-pre-wrap">{artifact.data}</div>
              ) : (
                <pre className="overflow-x-auto text-xs font-mono text-blue-300 p-4 rounded-xl bg-slate-950 border border-slate-800">
                  {JSON.stringify(artifact.data, null, 2)}
                </pre>
              )}
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="p-3 border-t border-slate-800 bg-slate-900/80 flex items-center justify-between text-xs pb-safe">
          <span className="text-[11px] text-slate-400">Export Artifact:</span>
          <div className="flex items-center gap-2">
            {['Markdown', 'JSON'].map((fmt) => (
              <button
                key={fmt}
                onClick={() => handleDownload(fmt.toLowerCase() as any)}
                className="px-2.5 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 text-[10px] font-bold text-slate-300 hover:text-white border border-slate-700 transition-all"
              >
                .{fmt}
              </button>
            ))}
          </div>
        </div>
      </motion.aside>
    </>
  );
}
