'use client';

import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  X,
  Maximize2,
  Minimize2,
  Copy,
  Check,
  Download,
  FileText,
  FileCode,
  Layers,
  HelpCircle,
  Sparkles,
  RotateCw,
  CheckCircle2,
  XCircle,
  ExternalLink
} from 'lucide-react';
import { useToast } from '@/components/ui/Toast';

interface ArtifactProps {
  isOpen: boolean;
  onClose: () => void;
  artifact: {
    id: string;
    title: string;
    type: 'FLASHCARDS' | 'MCQ' | 'NOTES' | 'REPORT' | 'QUESTIONS';
    data: any;
    createdAt?: string;
  } | null;
}

export default function ClaudeArtifactCanvas({
  isOpen,
  onClose,
  artifact
}: ArtifactProps) {
  const { success } = useToast();
  const [copied, setCopied] = useState(false);
  const [isExpanded, setIsExpanded] = useState(false);

  // Flashcards state: active card index and flipped status
  const [activeCardIdx, setActiveCardIdx] = useState(0);
  const [isFlipped, setIsFlipped] = useState(false);

  // MCQ state: selected answers map { [questionIdx]: selectedOptionIdx }
  const [mcqAnswers, setMcqAnswers] = useState<{ [qIdx: number]: number }>({});

  if (!isOpen || !artifact) return null;

  const handleCopy = () => {
    const textContent = JSON.stringify(artifact.data, null, 2);
    navigator.clipboard.writeText(textContent);
    setCopied(true);
    success('Copied to Clipboard!', 'Study artifact copied in clean format.');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = (format: 'md' | 'txt' | 'json') => {
    let content = '';
    let mime = 'text/plain';

    if (format === 'json') {
      content = JSON.stringify(artifact.data, null, 2);
      mime = 'application/json';
    } else {
      content = `# ${artifact.title}\n\nGenerated by EduAgent Pro\n\n${JSON.stringify(artifact.data, null, 2)}`;
    }

    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${artifact.title.replace(/\s+/g, '_').toLowerCase()}.${format}`;
    a.click();
    URL.revokeObjectURL(url);
    success('Export Complete', `Saved as .${format.toUpperCase()}`);
  };

  return (
    <motion.aside
      initial={{ x: 600, opacity: 0 }}
      animate={{ x: 0, opacity: 1 }}
      exit={{ x: 600, opacity: 0 }}
      transition={{ type: 'spring', damping: 25, stiffness: 220 }}
      className={`fixed top-20 right-4 bottom-4 z-40 flex flex-col rounded-[32px] bg-[#080B16]/95 backdrop-blur-3xl border border-white/[0.15] shadow-[0_20px_70px_rgba(0,0,0,0.7)] overflow-hidden select-none transition-all ${
        isExpanded ? 'w-[calc(100vw-2rem)] lg:w-[860px]' : 'w-[calc(100vw-2rem)] sm:w-[480px] lg:w-[540px]'
      }`}
    >
      {/* Top Action Bar */}
      <div className="p-4 border-b border-white/[0.08] bg-slate-950/60 flex items-center justify-between gap-3">
        <div className="flex items-center gap-2.5 min-w-0">
          <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-cyan-400 via-indigo-500 to-purple-500 flex items-center justify-center text-white shadow-md shadow-purple-500/25 flex-shrink-0">
            <Sparkles className="w-4 h-4" />
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <span className="text-[10px] font-black uppercase tracking-wider px-2 py-0.5 rounded-full bg-cyan-400/20 text-cyan-300 border border-cyan-400/30">
                Claude Artifact
              </span>
              <span className="text-[10px] font-bold text-slate-400">Interactive Preview</span>
            </div>
            <h3 className="text-sm font-black text-white truncate mt-0.5">{artifact.title}</h3>
          </div>
        </div>

        {/* Export Pills & Window Controls */}
        <div className="flex items-center gap-1.5 flex-shrink-0">
          <button
            onClick={handleCopy}
            className="p-2 rounded-xl bg-white/[0.06] hover:bg-white/[0.12] text-slate-300 hover:text-white border border-white/[0.1] text-xs font-semibold flex items-center gap-1 transition-colors"
            title="Copy Content"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
          </button>

          <button
            onClick={() => handleDownload('md')}
            className="p-2 rounded-xl bg-white/[0.06] hover:bg-white/[0.12] text-slate-300 hover:text-white border border-white/[0.1] text-xs font-semibold flex items-center gap-1 transition-colors"
            title="Export as Markdown"
          >
            <Download className="w-3.5 h-3.5" />
          </button>

          <button
            onClick={() => setIsExpanded(!isExpanded)}
            className="p-2 rounded-xl bg-white/[0.06] hover:bg-white/[0.12] text-slate-300 hover:text-white border border-white/[0.1] transition-colors hidden sm:block"
            title={isExpanded ? 'Collapse Canvas' : 'Expand Canvas'}
          >
            {isExpanded ? <Minimize2 className="w-3.5 h-3.5" /> : <Maximize2 className="w-3.5 h-3.5" />}
          </button>

          <button
            onClick={onClose}
            className="p-2 rounded-xl bg-white/[0.06] hover:bg-rose-500/20 text-slate-300 hover:text-rose-400 border border-white/[0.1] transition-colors"
            title="Close Artifact"
          >
            <X className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Main Interactive Artifact Content */}
      <div className="flex-1 overflow-y-auto p-5 space-y-6">
        {/* ========================================================== */}
        {/* FLASHCARDS INTERACTIVE VIEW                                */}
        {/* ========================================================== */}
        {artifact.type === 'FLASHCARDS' && Array.isArray(artifact.data?.flashcards || artifact.data) && (
          (() => {
            const cards = artifact.data?.flashcards || artifact.data;
            const currentCard = cards[activeCardIdx] || { question: 'No question', answer: 'No answer' };

            return (
              <div className="space-y-5">
                <div className="flex items-center justify-between text-xs font-bold text-slate-300">
                  <span className="flex items-center gap-1.5">
                    <Layers className="w-4 h-4 text-purple-400" /> Card {activeCardIdx + 1} of {cards.length}
                  </span>
                  <span className="text-[11px] text-slate-400">Click card to flip</span>
                </div>

                {/* 3D Flip Card */}
                <div
                  onClick={() => setIsFlipped(!isFlipped)}
                  className="perspective-1000 w-full h-72 cursor-pointer select-none"
                >
                  <motion.div
                    animate={{ rotateY: isFlipped ? 180 : 0 }}
                    transition={{ duration: 0.5, ease: 'easeInOut' }}
                    className="transform-style-3d relative w-full h-full rounded-3xl"
                  >
                    {/* Front: Question */}
                    <div className="backface-hidden absolute inset-0 p-6 rounded-3xl bg-gradient-to-br from-indigo-950/80 via-slate-900/90 to-purple-950/80 border border-cyan-500/30 shadow-2xl flex flex-col justify-between">
                      <div className="flex items-center justify-between">
                        <span className="text-[10px] font-black uppercase px-2 py-0.5 rounded-full bg-cyan-400/20 text-cyan-300 border border-cyan-400/30">
                          Question / Term
                        </span>
                        <RotateCw className="w-4 h-4 text-slate-400" />
                      </div>
                      <p className="text-base sm:text-lg font-extrabold text-white text-center leading-relaxed">
                        {currentCard.question || currentCard.front}
                      </p>
                      <div className="text-center text-[11px] text-cyan-300 font-medium">
                        Click to reveal explanation
                      </div>
                    </div>

                    {/* Back: Answer */}
                    <div className="backface-hidden rotate-y-180 absolute inset-0 p-6 rounded-3xl bg-gradient-to-br from-purple-950/90 via-slate-900/90 to-pink-950/90 border border-pink-500/30 shadow-2xl flex flex-col justify-between">
                      <div className="flex items-center justify-between">
                        <span className="text-[10px] font-black uppercase px-2 py-0.5 rounded-full bg-pink-400/20 text-pink-300 border border-pink-400/30">
                          Pedagogical Answer
                        </span>
                        <RotateCw className="w-4 h-4 text-slate-400" />
                      </div>
                      <p className="text-sm sm:text-base font-semibold text-slate-100 text-center leading-relaxed">
                        {currentCard.answer || currentCard.back}
                      </p>
                      <div className="text-center text-[11px] text-pink-300 font-medium">
                        Click to flip back
                      </div>
                    </div>
                  </motion.div>
                </div>

                {/* Navigation Controls */}
                <div className="flex items-center justify-between gap-3 pt-2">
                  <button
                    disabled={activeCardIdx === 0}
                    onClick={() => {
                      setIsFlipped(false);
                      setActiveCardIdx((prev) => Math.max(0, prev - 1));
                    }}
                    className="px-4 py-2 rounded-xl bg-white/[0.06] hover:bg-white/[0.12] text-xs font-bold text-white border border-white/[0.1] disabled:opacity-30 transition-all"
                  >
                    ← Previous
                  </button>
                  <span className="text-xs font-bold text-slate-400">
                    {activeCardIdx + 1} / {cards.length}
                  </span>
                  <button
                    disabled={activeCardIdx === cards.length - 1}
                    onClick={() => {
                      setIsFlipped(false);
                      setActiveCardIdx((prev) => Math.min(cards.length - 1, prev + 1));
                    }}
                    className="px-4 py-2 rounded-xl bg-gradient-to-r from-indigo-500 to-purple-500 hover:opacity-95 text-xs font-bold text-white shadow-md shadow-purple-500/20 disabled:opacity-30 transition-all"
                  >
                    Next Card →
                  </button>
                </div>
              </div>
            );
          })()
        )}

        {/* ========================================================== */}
        {/* INTERACTIVE CLICKABLE MCQ QUIZ VIEW                       */}
        {/* ========================================================== */}
        {artifact.type === 'MCQ' && (
          <div className="space-y-6">
            {(artifact.data?.questions || artifact.data || []).map((q: any, qIdx: number) => {
              const selectedOpt = mcqAnswers[qIdx];
              const isAnswered = selectedOpt !== undefined;
              const isCorrect = isAnswered && selectedOpt === q.correctAnswerIndex;

              return (
                <div
                  key={qIdx}
                  className="p-5 rounded-2xl bg-white/[0.04] border border-white/[0.08] space-y-3 shadow-lg"
                >
                  <div className="flex items-start justify-between gap-2">
                    <p className="text-xs sm:text-sm font-bold text-white leading-snug">
                      <span className="text-cyan-400 mr-1.5">Q{qIdx + 1}.</span> {q.question}
                    </p>
                  </div>

                  <div className="space-y-2 pt-1">
                    {(q.options || []).map((opt: string, optIdx: number) => {
                      let btnStyle = 'bg-white/[0.03] border-white/[0.08] text-slate-300 hover:bg-white/[0.08]';
                      if (isAnswered) {
                        if (optIdx === q.correctAnswerIndex) {
                          btnStyle = 'bg-emerald-500/20 border-emerald-500/50 text-emerald-200 font-bold';
                        } else if (selectedOpt === optIdx) {
                          btnStyle = 'bg-rose-500/20 border-rose-500/50 text-rose-200 font-bold';
                        } else {
                          btnStyle = 'opacity-40 bg-white/[0.01] border-white/[0.05] text-slate-500';
                        }
                      }

                      return (
                        <button
                          key={optIdx}
                          disabled={isAnswered}
                          onClick={() => setMcqAnswers((prev) => ({ ...prev, [qIdx]: optIdx }))}
                          className={`w-full p-3 rounded-xl border text-xs text-left flex items-center justify-between transition-all ${btnStyle}`}
                        >
                          <span>{opt}</span>
                          {isAnswered && optIdx === q.correctAnswerIndex && (
                            <CheckCircle2 className="w-4 h-4 text-emerald-400 flex-shrink-0" />
                          )}
                          {isAnswered && selectedOpt === optIdx && optIdx !== q.correctAnswerIndex && (
                            <XCircle className="w-4 h-4 text-rose-400 flex-shrink-0" />
                          )}
                        </button>
                      );
                    })}
                  </div>

                  {/* Immediate Pedagogical Explanation */}
                  {isAnswered && q.explanation && (
                    <motion.div
                      initial={{ opacity: 0, height: 0 }}
                      animate={{ opacity: 1, height: 'auto' }}
                      className={`p-3 rounded-xl text-[11px] leading-relaxed border ${
                        isCorrect
                          ? 'bg-emerald-950/30 border-emerald-500/30 text-emerald-200'
                          : 'bg-indigo-950/30 border-purple-500/30 text-purple-200'
                      }`}
                    >
                      <strong className="block mb-0.5">{isCorrect ? '✅ Well done!' : '💡 Explanation:'}</strong>
                      {q.explanation}
                    </motion.div>
                  )}
                </div>
              );
            })}
          </div>
        )}

        {/* ========================================================== */}
        {/* REVISION NOTES / GENERAL PEDAGOGICAL VIEW                  */}
        {/* ========================================================== */}
        {artifact.type !== 'FLASHCARDS' && artifact.type !== 'MCQ' && (
          <div className="p-6 rounded-2xl bg-white/[0.03] border border-white/[0.08] space-y-4 text-slate-200 text-xs sm:text-sm leading-relaxed shadow-lg">
            {typeof artifact.data === 'string' ? (
              <div className="whitespace-pre-wrap">{artifact.data}</div>
            ) : (
              <pre className="overflow-x-auto text-xs font-mono text-cyan-200 p-4 rounded-xl bg-black/40 border border-white/[0.05]">
                {JSON.stringify(artifact.data, null, 2)}
              </pre>
            )}
          </div>
        )}
      </div>

      {/* Artifact Footer Export Bar */}
      <div className="p-3 border-t border-white/[0.08] bg-slate-950/60 flex items-center justify-between text-xs">
        <span className="text-[11px] text-slate-400 font-medium">
          Ready for export:
        </span>
        <div className="flex items-center gap-2">
          {['PDF', 'DOCX', 'Markdown'].map((fmt) => (
            <button
              key={fmt}
              onClick={() => handleDownload('md')}
              className="px-2.5 py-1 rounded-lg bg-white/[0.06] hover:bg-white/[0.12] text-[10px] font-bold text-slate-300 hover:text-white border border-white/[0.1] transition-all"
            >
              .{fmt}
            </button>
          ))}
        </div>
      </div>
    </motion.aside>
  );
}
